export function translateUi(locale: Locale, text: string, ...values: (string | number)[]) {
  const template = locale === "en" ? english[text] ?? text : text;
  return template.replace(/\{(\d+)\}/g, (_, index) => String(values[Number(index)] ?? ""));
}
